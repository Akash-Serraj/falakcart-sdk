/**
 * Mirrors the platform's country list into the components package.
 *
 *   node falak-components/scripts/sync-countries.mjs [path/to/countries.ts]
 *
 * The platform's frontend/src/utils/countries.ts is the canonical dataset
 * (the admin's phone fields and config/countries.php are already derived from
 * it). The storefront components cannot import from the admin build, so the
 * parts a storefront needs — code, dial code, English and Arabic names — are
 * copied into src/lib/countries.js in the same order: KSA first, then GCC,
 * then the Arab League, then the rest of the world. Re-run after editing the
 * source file.
 *
 * The SDK lives in its own repository now, so the source is looked for in a
 * `falakcart` checkout beside this one; pass the file's path to read it from
 * anywhere else.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const source = process.argv[2]
    ? resolve(process.cwd(), process.argv[2])
    : resolve(here, '../../../falakcart/frontend/src/utils/countries.ts');
const target = resolve(here, '../src/lib/countries.js');

const ts = readFileSync(source, 'utf8');
const rows = [];
const entry = /\{\s*code:\s*"([A-Z]{2})",\s*dialCode:\s*"(\+\d+)",\s*nameEn:\s*"([^"]+)",\s*nameAr:\s*"([^"]+)"/g;
for (const match of ts.matchAll(entry)) {
    const [, code, dial, en, ar] = match;
    rows.push(`    ['${code}', '${dial}', ${JSON.stringify(en)}, ${JSON.stringify(ar)}],`);
}
if (rows.length < 200) {
    console.error(`sync-countries: only ${rows.length} entries parsed from ${source} — format changed?`);
    process.exit(1);
}

const out = `/**
 * GENERATED by scripts/sync-countries.mjs from frontend/src/utils/countries.ts
 * — do not edit by hand; edit the source and re-run the script.
 *
 * Each row is [ISO code, dial code, English name, Arabic name], in the
 * platform's display order: KSA, the GCC, the Arab League, then the rest of
 * the world alphabetically.
 */
export const COUNTRIES = [
${rows.join('\n')}
].map(([code, dial, nameEn, nameAr]) => ({ code, dial, nameEn, nameAr }));

/** Longest dial code first, so "+1264…" resolves to Anguilla rather than "+1". */
const BY_DIAL_LENGTH = [...COUNTRIES].sort((a, b) => b.dial.length - a.dial.length);

/** The country whose dial code starts an E.164 number, or undefined. */
export function countryForPhone(phone) {
    const value = String(phone || '');
    return BY_DIAL_LENGTH.find(country => value.startsWith(country.dial));
}

/** Localised country name — Arabic when the storefront is Arabic. */
export function countryName(country, locale) {
    return locale === 'ar' ? country.nameAr : country.nameEn;
}

/**
 * Regional-indicator flag for an ISO code. Platforms without flag glyphs
 * (Windows, notably) fall back to the two letters, which still reads.
 */
export function countryFlag(code) {
    return String(code).toUpperCase().replace(/./g, ch => String.fromCodePoint(0x1F1E6 + ch.charCodeAt(0) - 65));
}
`;

writeFileSync(target, out.replace(/\r\n/g, '\n'), 'utf8');
console.log(`sync-countries: wrote ${rows.length} countries to ${target}`);
